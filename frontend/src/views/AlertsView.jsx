import React, { useState, useEffect } from 'react';
import { AlertTriangle, ShieldAlert, Info, Filter, RefreshCcw } from 'lucide-react';
import { apiUrl } from '../api';

export default function AlertsView() {
  const [alerts, setAlerts] = useState([]);
  const [filterSeverity, setFilterSeverity] = useState('All');
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetchAlerts();
  }, []);

  const fetchAlerts = async () => {
    setLoading(true);
    try {
      const response = await fetch(apiUrl('/api/alerts'));
      const data = await response.json();
      setAlerts(data);
    } catch (err) {
      console.error('Failed to fetch alerts:', err);
    } finally {
      setLoading(false);
    }
  };

  const filteredAlerts = alerts.filter(a => {
    if (filterSeverity === 'All') return true;
    return a.severity === filterSeverity;
  });

  return (
    <div className="space-y-6">
      {/* Title & Filter Controls */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 p-5 rounded-lg bg-white border border-slate-200 shadow-sm">
        <div>
          <h3 className="text-base font-bold text-slate-900 flex items-center gap-2">
            <AlertTriangle className="w-5 h-5 text-amber-700" /> Automated Environmental Alerts Log
          </h3>
          <p className="text-xs text-slate-500 mt-0.5">Continuous notifications generated by statutory threshold violations and anomaly classifiers</p>
        </div>

        <div className="flex items-center gap-2">
          <Filter className="w-4 h-4 text-slate-400" />
          {['All', 'Critical', 'Warning', 'Info'].map((sev) => (
            <button
              key={sev}
              onClick={() => setFilterSeverity(sev)}
              className={`text-xs font-semibold px-3 py-1.5 rounded-md transition ${
                filterSeverity === sev
                  ? 'bg-[#1b4332] text-white font-bold'
                  : 'bg-white border border-slate-300 text-slate-700 hover:bg-slate-50'
              }`}
            >
              {sev}
            </button>
          ))}
          <button
            onClick={fetchAlerts}
            className="p-1.5 rounded-md bg-white border border-slate-300 text-slate-600 hover:text-slate-900 transition"
            title="Refresh Alert Stream"
          >
            <RefreshCcw className="w-4 h-4" />
          </button>
        </div>
      </div>

      {/* Alerts Feed */}
      {loading ? (
        <div className="flex items-center justify-center h-64 text-slate-500 gap-2">
          <RefreshCcw className="w-5 h-5 animate-spin text-emerald-800" />
          <span className="text-sm">Fetching active notifications...</span>
        </div>
      ) : filteredAlerts.length > 0 ? (
        <div className="space-y-3">
          {filteredAlerts.map((alt, idx) => {
            const isCritical = alt.severity === 'Critical';
            const isWarning = alt.severity === 'Warning';
            return (
              <div
                key={idx}
                className={`p-4 rounded-lg border border-slate-200 bg-white transition flex items-start justify-between gap-4 shadow-xs ${
                  isCritical
                    ? 'border-l-4 border-l-red-600'
                    : isWarning
                    ? 'border-l-4 border-l-amber-600'
                    : 'border-l-4 border-l-emerald-700'
                }`}
              >
                <div className="flex items-start gap-3">
                  <div className={`p-2 rounded-md shrink-0 mt-0.5 ${
                    isCritical ? 'bg-red-50 text-red-700' : isWarning ? 'bg-amber-50 text-amber-700' : 'bg-emerald-50 text-emerald-800'
                  }`}>
                    {isCritical ? <ShieldAlert className="w-5 h-5" /> : isWarning ? <AlertTriangle className="w-5 h-5" /> : <Info className="w-5 h-5" />}
                  </div>
                  <div>
                    <div className="flex items-center gap-2">
                      <h4 className="text-sm font-bold text-slate-900">{alt.title}</h4>
                      <span className="text-[10px] font-semibold px-2 py-0.5 rounded-md bg-slate-100 border border-slate-200 text-slate-600">
                        {alt.category}
                      </span>
                    </div>
                    <p className="text-xs text-slate-600 mt-1 leading-relaxed">{alt.message}</p>
                  </div>
                </div>

                <div className="text-right shrink-0">
                  <span className={`text-[10px] font-bold px-2 py-0.5 rounded-md uppercase ${
                    isCritical ? 'bg-red-50 text-red-800 border border-red-200' : isWarning ? 'bg-amber-50 text-amber-800 border border-amber-200' : 'bg-slate-100 text-slate-600 border border-slate-200'
                  }`}>
                    {alt.severity}
                  </span>
                  <span className="block text-[10px] text-slate-400 mt-1 font-mono">{alt.timestamp || 'Active'}</span>
                </div>
              </div>
            );
          })}
        </div>
      ) : (
        <div className="p-8 rounded-lg bg-white border border-slate-200 shadow-sm text-center text-slate-500 text-xs">
          No active alerts matching the selected severity filter.
        </div>
      )}
    </div>
  );
}
